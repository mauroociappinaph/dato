#!/usr/bin/env python3
"""
Eval Report Generator - agent-evaluation
Generates a human-readable Markdown report from eval results.

Usage:
    python report.py results.json
    python report.py results.json --output report.md
"""

import argparse
import json
import sys
from pathlib import Path


def generate_report(results: dict) -> str:
    """Generate a Markdown report from eval results."""
    lines = []
    lines.append(f"# 📊 Eval Report: {results['suite']}")
    lines.append("")
    lines.append(f"**Model:** `{results['model']}`")
    lines.append(f"**Runs per test:** {results['runs_per_test']}")
    lines.append(f"**Total tests:** {results['total_tests']}")
    lines.append("")

    # Overall score
    pass_rate = results["overall_pass_rate"]
    emoji = "✅" if pass_rate >= 0.8 else "⚠️" if pass_rate >= 0.5 else "❌"
    lines.append(f"## {emoji} Overall Pass Rate: {pass_rate * 100:.1f}%")
    lines.append(f"**Avg Latency:** {results['avg_latency_ms']:.0f}ms")
    lines.append("")

    # Test results table
    lines.append("## Results by Test")
    lines.append("")
    lines.append("| Test | Pass Rate | Passes | Latency (avg) | Latency (p95) |")
    lines.append("|------|-----------|--------|---------------|---------------|")

    for test in results["tests"]:
        pr = test["pass_rate"]
        icon = "✅" if pr >= 0.8 else "⚠️" if pr >= 0.5 else "❌"
        lines.append(
            f"| {icon} {test['name']} "
            f"| {pr * 100:.0f}% "
            f"| {test['passes']}/{test['runs']} "
            f"| {test['latency_avg_ms']:.0f}ms "
            f"| {test['latency_p95_ms']:.0f}ms |"
        )

    lines.append("")

    # Latency histogram (ASCII)
    lines.append("## ⏱️ Latency Distribution")
    lines.append("```")
    all_latencies = []
    for test in results["tests"]:
        for detail in test.get("details", []):
            all_latencies.append(detail["latency_ms"])

    if all_latencies:
        min_l = min(all_latencies)
        max_l = max(all_latencies)
        bucket_count = min(10, len(all_latencies))
        bucket_size = max(1, (max_l - min_l) / bucket_count)

        buckets = [0] * bucket_count
        for lat in all_latencies:
            idx = min(int((lat - min_l) / bucket_size), bucket_count - 1)
            buckets[idx] += 1

        max_count = max(buckets) if buckets else 1
        for i, count in enumerate(buckets):
            lower = min_l + i * bucket_size
            upper = lower + bucket_size
            bar = "█" * int(count / max_count * 30)
            lines.append(f"  {lower:7.0f}-{upper:7.0f}ms | {bar} ({count})")

    lines.append("```")
    lines.append("")

    # Failures detail
    failures = []
    for test in results["tests"]:
        for detail in test.get("details", []):
            if not detail["passed"]:
                failed_checks = [
                    c for c in detail["checks"] if not c["passed"]
                ]
                failures.append({
                    "test": test["name"],
                    "run": detail["run"],
                    "reasons": [c["reason"] for c in failed_checks],
                })

    if failures:
        lines.append("## ❌ Failure Details")
        lines.append("")
        for f in failures[:10]:  # Max 10 to keep report readable
            reasons = ", ".join(f["reasons"])
            lines.append(f"- **{f['test']}** (run {f['run']}): {reasons}")
        if len(failures) > 10:
            lines.append(f"- ... and {len(failures) - 10} more failures")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by agent-evaluation (THE DUDE)*")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="Generate eval report from results JSON"
    )
    parser.add_argument("results", help="Path to JSON results file")
    parser.add_argument("--output", "-o", default=None,
                        help="Save report to file")
    args = parser.parse_args()

    data = json.loads(Path(args.results).read_text(encoding="utf-8"))
    report = generate_report(data)

    print(report)

    if args.output:
        Path(args.output).write_text(report, encoding="utf-8")
        print(f"\n✅ Report saved to {args.output}", file=sys.stderr)

    return 0


if __name__ == "__main__":
    sys.exit(main())
